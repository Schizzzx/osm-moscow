#------------------------------------------------------------------------------------------------------------------------
# check.py - независимая проверка нашей утилиты
# кароче берем те же файлы что у утилиты (points.txt и district.txt) и считаем все готовой библиотекой shapely
# потом запускаем нашу утилиту geo.py и сравнивам что получилось. типа сверяемся с ответами в конце учебника
# shapely есть ТОЛЬКО в этом файле. в самой утилите его нет
# запуск: python check.py data/points.txt data/district.txt
#
# 0. подключаем библиотеки
#------------------------------------------------------------------------------------------------------------------------

import sys
import math
import subprocess
from shapely.geometry import MultiPoint, Polygon, Point
from shapely.ops import unary_union


#------------------------------------------------------------------------------------------------------------------------
# 1. функции-помощники
# вкраце, тут читаем файлы6 запускаем geo.py и сравниваем ответы
#------------------------------------------------------------------------------------------------------------------------

# рид_поинтс - читаем точки. точка это [номер, x, y]
def read_points(filename):
    pts = []
    f = open(filename, encoding="utf-8")
    for line in f:
        line = line.strip()
        if line == "":
            continue
        a = line.split()
        pts.append([a[0], int(a[1]), int(a[2])])
    f.close()
    return pts


#------------------------------------------------------------------------------------------------------------------------
# рид_район - читаем район. кольца разделены пустой строкой
# тут дециметры
def read_rayon(filename):
    kolca = []
    tek = []
    f = open(filename, encoding="utf-8")
    for line in f:
        line = line.strip()
        if line == "":
            if len(tek) > 0:
                kolca.append(tek)
                tek = []
            continue
        a = line.split()
        tek.append((int(a[0]), int(a[1])))
    f.close()
    if len(tek) > 0:
        kolca.append(tek)
    return kolca


#------------------------------------------------------------------------------------------------------------------------
# запуск - запускаем нашу утилиту тем же питоном которым запущен check.py и забираем что она напечаттала
# -X utf8 и encoding="utf-8" это для винды. там без этого русские буквы в выводе ломаются и все падает
def zapusk(args):
    res = subprocess.run([sys.executable, "-X", "utf8", "geo.py"] + args, capture_output=True, encoding="utf-8")
    return res.stdout


#------------------------------------------------------------------------------------------------------------------------
# взять - ищем в выводе строчку которая начинается с nachalo и берем то что после двоеточия
def vzyat(text, nachalo):
    for line in text.splitlines():
        if line.startswith(nachalo):
            return line.split(":", 1)[1].strip()
    return None


#------------------------------------------------------------------------------------------------------------------------
# тут считаем сколько пунктов не сошлось. глобальная переменная - как в geo.py
oshibok = 0


#------------------------------------------------------------------------------------------------------------------------
# сравнить - печатаем сравнение в одну строчку. если не сошлось - +1 к oshibok
def sravnit(chto, nashe, ihnee):
    global oshibok
    if nashe == ihnee:
        print("  ", chto, "| утилита:", nashe, "| проверка:", ihnee, "| сошлось")
    else:
        print("  ", chto, "| утилита:", nashe, "| проверка:", ihnee, "| НЕ СОШЛОСЬ")
        oshibok = oshibok + 1


#------------------------------------------------------------------------------------------------------------------------
# 2. запуск
# вкраце, проверяем что файлы передали и читаем их
#------------------------------------------------------------------------------------------------------------------------

if len(sys.argv) < 3:
    print("надо так: python check.py <точки.txt> <район.txt>")
    sys.exit()

file_t = sys.argv[1]
file_r = sys.argv[2]

pts = read_points(file_t)
kolca = read_rayon(file_r)
print("точек:", len(pts), "колец в районе:", len(kolca))


#------------------------------------------------------------------------------------------------------------------------
# 3. проверяем оболочку
# вкраце, shapely convex_hull против нашего hull
#------------------------------------------------------------------------------------------------------------------------

# 1. оболочка
print("1. оболочка (shapely convex_hull)")
koord = []
for p in pts:
    koord.append((p[1], p[2]))
ob = MultiPoint(koord).convex_hull

# shapely ретернит разные штуки - многоугольник, отрезок, точку или вообще пустоту
if ob.is_empty:
    verh = 0
    s2 = 0
elif ob.geom_type == "Polygon":
    # в shapely последняя точка кольца повторяет первую (как в geojson - видимо это у них семейное) поэтому минус 1
    verh = len(ob.exterior.coords) - 1
    s2 = round(ob.area * 2)
elif ob.geom_type == "LineString":
    verh = len(ob.coords)
    s2 = 0
else:
    verh = 1
    s2 = 0

out = zapusk(["hull", file_t])
sravnit("вершин оболочки", int(vzyat(out, "вершин оболочки")), verh)
nash_s2 = vzyat(out, "удвоенная площадь")
if nash_s2 is None:
    nash_s2 = 0
sravnit("удвоенная площадь (дм2)", int(nash_s2), s2)


#------------------------------------------------------------------------------------------------------------------------
# 4. проверяем район и точки внутри
# вкраце, shapely contains против нашего луча
#------------------------------------------------------------------------------------------------------------------------

# 2. район и точки внутри
print("2. район (shapely Polygon + contains)")
kuski = []
dyrki = []
for k in kolca:
    if len(k) < 3:
        continue
    pol = Polygon(k)
    # is_ccw - готовая проверка из shapely. идет ли кольцо против часовой
    if pol.exterior.is_ccw:
        kuski.append(pol)
    else:
        dyrki.append(pol)
rayon = unary_union(kuski)
if len(dyrki) > 0:
    rayon = rayon.difference(unary_union(dyrki))

vn = 0
na_granice = 0
for p in pts:
    t = Point(p[1], p[2])
    if rayon.contains(t):
        vn = vn + 1
    # отдельно смотрим нет ли точек ровно на границе. там ответ зависит от способа
    if not rayon.is_empty and rayon.boundary.distance(t) == 0:
        na_granice = na_granice + 1

out = zapusk(["inside", file_t, file_r])
sravnit("точек внутри", int(vzyat(out, "внутри")), vn)
sravnit("удвоенная площадь района (дм2)", int(vzyat(out, "удвоенная площадь района")), round(rayon.area * 2))
print("   точек ровно на границе района (по shapely):", na_granice)


#------------------------------------------------------------------------------------------------------------------------
# 5. проверяем ближайшую пару
# вкраце, разделяй и властвуй против перебора
#------------------------------------------------------------------------------------------------------------------------

# 3. ближайшая пара
# перебор тут свой отдельный. а еще сравниваем с перебором самой утилиты (--brute)
print("3. ближайшая пара")
if len(pts) < 2:
    print("   точек меньше двух, сравнивать нечего")
else:
    best = -1
    for i in range(len(pts)):
        for j in range(i + 1, len(pts)):
            d = math.hypot(pts[i][1] - pts[j][1], pts[i][2] - pts[j][2])
            if best == -1 or d < best:
                best = d
    moy_perebor = best / 10

    out1 = zapusk(["closest", file_t])
    out2 = zapusk(["closest", file_t, "--brute"])
    dc = float(vzyat(out1, "расстояние"))
    br = float(vzyat(out2, "расстояние"))
    sravnit("расстояние (м), разделяй и властвуй vs --brute утилиты", dc, br)
    # тут сравниваем с маленьким допуском. hypot и sqrt могут разойтись в последней цифре
    if abs(dc - moy_perebor) < 1e-9:
        sravnit("расстояние (м), разделяй и властвуй vs перебор check.py", dc, dc)
    else:
        sravnit("расстояние (м), разделяй и властвуй vs перебор check.py", dc, moy_perebor)
    print("   пара у утилиты:", vzyat(out1, "объекты"), "| у --brute:", vzyat(out2, "объекты"))
    print("   вычислений расстояния: разделяй и властвуй", vzyat(out1, "вычислений расстояния"),
          "| перебор", vzyat(out2, "вычислений расстояния"))


#------------------------------------------------------------------------------------------------------------------------
# 6. итог
# вкраце, если oshibok = 0 то все сошлось и можно спать
#------------------------------------------------------------------------------------------------------------------------

print()
if oshibok == 0:
    print("ИТОГ: все сошлось")
else:
    print("ИТОГ: не сошлось пунктов:", oshibok)
    print("но вобще у меня все работало, а это типа один из сильнейших аргументов что все норм, как всем известно")
