# длина отрезка между двумя точками. единицы те же что у координат - дециметры
# тут уже дробные числа но это просто длина а не предикат
def dlina(a, b):
    dx = b[0] - a[0]
    dy = b[1] - a[1]
    return math.sqrt(dx * dx + dy * dy)


