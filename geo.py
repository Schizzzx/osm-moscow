# рид_район - функция для чтения района.
# используем geojson, но в нем кооординаты идут наоборот - долгота-широта
# бываетдва типа районов. полигон - один кусок. мультгон - несколько кусков.
# ретёрнит несколько колец - список широт-долгот (широты и долготы, я оставил версию слева ради кеков)
# и список tip, где написано какое кольцо внешнее, а какое дырка
def read_rayon(filename):
    f = open(filename, encoding="utf-8")
    data = json.load(f)
    f.close()

    geom = data["features"][0]["geometry"]

    # если кусок один, делаем из него список из одного куска, чтобы дальше было одинаково
    if geom["type"] == "Polygon":
        kuski = [geom["coordinates"]]
    else:
        kuski = geom["coordinates"]

    kolca = []
    tip = []

    # цикл по кускам района
    for kusok in kuski:
        # цикл по кольцам внутри куска
        for i in range(len(kusok)):
            kolco = []
            # переставляем местами потому что geojson деает все наоборот
            for p in kusok[i]:
                kolco.append([p[1], p[0]])

            # еще у меня почему то последняя строчка копирует первую - ее быть не должно - выкидываем
            # UPD: загуглил - это опять geojson чудит...
            if kolco[0] == kolco[-1]:
                kolco.pop()

            kolca.append(kolco)

            # в каждом куске первое кольцо внешнее, а остальные - дырки
            if i == 0:
                tip.append("внешнее")
            else:
                tip.append("дырка")

    return kolca, tip


#------------------------------------------------------------------------------------------------------------------------
# тут функция которая переводит широту и долготу в координаты
# формула как из задания
# x = R * (долгота - долгота0) * cos(широта0), y = R * (широта - широта0)
# что бы углы были в радианах - math.radian
# и множим на десять что бы перевести метры в дециметры. (ого эта величина пригодилась мне хоть где то после второго класа хахах)
def proj(lat, lon, lat0, lon0):
    x = R * math.radians(lon - lon0) * math.cos(math.radians(lat0))
    y = R * math.radians(lat - lat0)
    x = round(x * 10)
    y = round(y * 10)
    return x, y


#------------------------------------------------------------------------------------------------------------------------
# формула шнурования - двойная плозадь кольца
# если обходить кольцо против часовой - получится плюс
# если по - получится минус
def ploshad2(kolco):
    s = 0
    n = len(kolco)
    for i in range(n):
        x1 = kolco[i][0]
        y1 = kolco[i][1]
        # мы берем следующую точку. а для последней точки - последующая точка это первая точка. кольцо так то замкнутое
        x2 = kolco[(i + 1) % n][0]
        y2 = kolco[(i + 1) % n][1]
        s = s + x1 * y2 - x2 * y1
    return s


