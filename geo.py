# поворот. идем из a в b потом в c - куда свернули?
# больше 0 - налево. меньше 0 - направо. 0 - все три на одной прямой
def povorot(a, b, c):
    return (b[0] - a[0]) * (c[1] - a[1]) - (b[1] - a[1]) * (c[0] - a[0])


#------------------------------------------------------------------------------------------------------------------------
# выпуклая оболочка монотонной цепочкой по алгоритму эндрю
# сначла сортируем точки слева направо6 потом строим нижнюю половину и верхнюю
# ретернит два списка - различные точки и вершины оболочки против часовой
def obolochka(pts):
    # sorted сортирует по x. а если x одинаковый то по y
    pts2 = sorted(pts)

    # выкидываем одинаковые точки - после сортировки они стоят рядом
    raz = []
    for p in pts2:
        if len(raz) > 0 and raz[-1][0] == p[0] and raz[-1][1] == p[1]:
            continue
        raz.append(p)

    # если точек меньше 3 то и строить нечего. оболочка это сами точки
    if len(raz) < 3:
        return raz, raz

    # нижняя половина - идем слева направо
    # если последние три точки поворачивают направо или стоят на одной прямой (<= 0) - среднюю выкидываем
    niz = []
    for p in raz:
        while len(niz) >= 2 and povorot(niz[-2], niz[-1], p) <= 0:
            niz.pop()
        niz.append(p)

    # верхняя половина - то же самое только справа налево
    verh = []
    for i in range(len(raz) - 1, -1, -1):
        p = raz[i]
        while len(verh) >= 2 and povorot(verh[-2], verh[-1], p) <= 0:
            verh.pop()
        verh.append(p)

    # последняя точка нижней половины это первая точка верхней (и наоборот)
    # поэтому у обеих выкидываем последнюю. иначе будет две одинаковых
    niz.pop()
    verh.pop()

    return raz, niz + verh


