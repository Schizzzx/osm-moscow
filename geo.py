# вкраце, эта команда ищет две самые близкие точки. двумя способами - "разделяй и властвуй" и перебор
#------------------------------------------------------------------------------------------------------------------------

# счетчик сколько раз считали расстояние
# это глобальная переменная. да я знаю что глобальные это плохо но так проще
schet = 0


#------------------------------------------------------------------------------------------------------------------------
# квадрат расстояния между двумя точками
# корень не берем - сравнивать можно и квадраты. а они целые и точные
# и каждый раз когда считаем - +1 к счетчику
def dist2(a, b):
    global schet
    schet = schet + 1
    dx = a[0] - b[0]
    dy = a[1] - b[1]
    return dx * dx + dy * dy


#------------------------------------------------------------------------------------------------------------------------
# перебор
# каждую точку сравниваем с каждой другой
# два цикла. второй начинается с i+1 что бы одну пару не считать два раза
# ретернит квадрат расстояния и две точки
def perebor(pts):
    best = -1
    pa = None
    pb = None
    for i in range(len(pts)):
        for j in range(i + 1, len(pts)):
            d = dist2(pts[i], pts[j])
            if best == -1 or d < best:
                best = d
                pa = pts[i]
                pb = pts[j]
    return best, pa, pb


#------------------------------------------------------------------------------------------------------------------------
# эта функция нужна только что бы сортировать полоску по y (отдаем ее в sort)
def po_y(p):
    return p[1]


#------------------------------------------------------------------------------------------------------------------------
# разделяй и властвуй
# px - точки которые уже отсортированы по x
def razdelyai(px):
    n = len(px)

    # если точек 3 или меньше то делить уже глупо - просто перебираем
    if n <= 3:
        return perebor(px)

    # делим пополам по номеру в списке. midx - это x линии раздела
    mid = n // 2
    midx = px[mid][0]
    levo = px[:mid]
    pravo = px[mid:]

    # рекурсия - эта же функция ищет лучшую пару в левой половине и в правой
    d1, a1, b1 = razdelyai(levo)
    d2, a2, b2 = razdelyai(pravo)

    # берем ту что лучше
    if d1 <= d2:
        best = d1
        pa = a1
        pb = b1
    else:
        best = d2
        pa = a2
        pb = b2

    # пара еще лучше может быть только через линию
    # поэтому берем полоску - точки которые от линии ближе чем best
    # best это квадрат расстояния. поэтому dx тоже возводим в квадрат
    polosa = []
    for p in px:
        dx = p[0] - midx
        if dx * dx < best:
            polosa.append(p)

    # сортируем полоску снизу вверх по y
    polosa.sort(key=po_y)

    # каждую точку полоски сравниваем с точками выше нее
    # как только по y ушли дальше чем best - дальше смотреть смысла нет. break
    # там выходит не больше 7 соседей на точку (это доказано не мной хахах)
    for i in range(len(polosa)):
        j = i + 1
        while j < len(polosa):
            dy = polosa[j][1] - polosa[i][1]
            if dy * dy >= best:
                break
            d = dist2(polosa[i], polosa[j])
            if d < best:
                best = d
                pa = polosa[i]
                pb = polosa[j]
            j = j + 1

    return best, pa, pb


