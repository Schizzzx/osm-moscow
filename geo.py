# на картинке все точки оболочка район и ближайшая пара
# matplotlib импортим прямо тут для оптимзации предыдущих функций
def plot(file_tochki, file_rayon, file_kartinka):
    import matplotlib
    # Agg - это что бы он не пытался открыть окно а просто сохранил картинку в файл
    matplotlib.use("Agg")
    import matplotlib.pyplot as plt

    pts = read_txt(file_tochki)
    kolca = read_district(file_rayon)

    # на картинке будем в км. дециметры это огромные числа
    # x это бывшие долготы, а y бывшие широты. вот так из долгот получились километры))
    fig, ax = plt.subplots(figsize=(10, 10))

    # 1. все точки серым
    xs = []
    ys = []
    for p in pts:
        xs.append(p[0] / 10000)
        ys.append(p[1] / 10000)
    ax.scatter(xs, ys, s=6, color="#8a8984", label="заправки (" + str(len(pts)) + ")")

    # 2. граница района. каждое кольцо рисуем отдельно
    # в конец кольца еще раз добавляем первую точку - иначе контур не замкнется
    for i in range(len(kolca)):
        k = kolca[i]
        xs = []
        ys = []
        for p in k:
            xs.append(p[0] / 10000)
            ys.append(p[1] / 10000)
        xs.append(k[0][0] / 10000)
        ys.append(k[0][1] / 10000)
        # подпись в легенду только у первого кольца. а то будет 5 одинаковых строчек
        if i == 0:
            ax.plot(xs, ys, color="#eb6834", linewidth=1.5, label="граница района (" + str(len(kolca)) + " колец)")
        else:
            ax.plot(xs, ys, color="#eb6834", linewidth=1.5)

    # 3. оболочка. берем из нашей же функции obolochka. название функции читается как американцы бы читали русские слова. вайб мема "о, да вы из англии"))
    raz, ob = obolochka(pts)
    if len(ob) > 0:
        xs = []
        ys = []
        for p in ob:
            xs.append(p[0] / 10000)
            ys.append(p[1] / 10000)
        xs.append(ob[0][0] / 10000)
        ys.append(ob[0][1] / 10000)
        ax.plot(xs, ys, color="#2a78d6", linewidth=2, label="выпуклая оболочка (" + str(len(ob)) + " вершин)")
        ax.scatter(xs, ys, s=25, color="#2a78d6")

    # 4. ближайшая пара. тоже нашей функцией razdelyai
    # на картинке пара сливается в одну точку (там метры ,а картинка на десятки км)
    # поэтому обводим ее большим кружком и подписываем
    if len(pts) >= 2:
        px = sorted(pts)
        d, a, b = razdelyai(px)
        ax.scatter([a[0] / 10000, b[0] / 10000], [a[1] / 10000, b[1] / 10000], s=250,
                   facecolors="none", edgecolors="#1baf7a", linewidths=2.5, label="ближайшая пара")
        tekst = "ближайшая пара: " + str(round(math.sqrt(d) / 10, 2)) + " м\n" + a[2] + "\n" + b[2]
        ax.annotate(tekst, xy=(a[0] / 10000, a[1] / 10000), xytext=(40, 60), textcoords="offset points",
                    fontsize=9, color="#0b0b0b",
                    bbox=dict(boxstyle="round", facecolor="white", edgecolor="#1baf7a"),
                    arrowprops=dict(arrowstyle="->", color="#1baf7a"))

    # всякая красота - одинаковый масштаб по осям (иначе карта сплющится) подписи сетка легенда
    ax.set_aspect("equal")
    ax.set_xlabel("x, км (на восток)")
    ax.set_ylabel("y, км (на север)")
    ax.set_title("точки: " + file_tochki + "   район: " + file_rayon)
    ax.grid(alpha=0.3)
    # best - matplotlib сам ищет место где легенда меньше всего мешает
    ax.legend(loc="best", fontsize=9)

    fig.savefig(file_kartinka, dpi=120, bbox_inches="tight")
    plt.close(fig)
    print("картинка сохранена:", file_kartinka)


