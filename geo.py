# рид_тхт - читает points.txt который нам сделал project
# в каждой строке номер x y
# ретернит список точек. точка это [x, y, номер] - x и y сразу переводим в int
def read_txt(filename):
    pts = []
    f = open(filename, encoding="utf-8")
    for line in f:
        line = line.strip()
        # пустые строки скипаем. мало ли
        if line == "":
            continue
        a = line.split()
        pts.append([int(a[1]), int(a[2]), a[0]])
    f.close()
    return pts


