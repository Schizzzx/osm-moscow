# она нам пргодится в команде project
# функция ретернит весь файл6 список точек и сколько точек пропустили и каких видов.
def read_points(filename):
    f = open(filename, encoding="utf-8")
    data = json.load(f)
    f.close()

    pts = []
    skip = 0
    vidy = {}

    # цикл. перебирвем объекты из выгрузки по одному
    for el in data["elements"]:
        nomer = el["type"] + "/" + str(el["id"])

        # лат и лон это координаты точек
        if "lat" in el:
            lat = el["lat"]
            lon = el["lon"]

        # у контура и составного объекта координаты - center
        elif "center" in el:
            lat = el["center"]["lat"]
            lon = el["center"]["lon"]
        # коррдинат нет - скипаем
        else:
            skip = skip + 1
            print("пропускаем", nomer, "- у него нет координат")
            continue

        pts.append([nomer, lat, lon])

        # считам сколько у нас точек, контуров и сособъектов
        if el["type"] in vidy:
            vidy[el["type"]] = vidy[el["type"]] + 1
        else:
            vidy[el["type"]] = 1

    return data, pts, skip, vidy


