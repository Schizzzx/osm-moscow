#!/bin/sh
#------------------------------------------------------------------------------------------------------------------------
# get_data.sh - качает данные и ставит библиотеки
# запускать из папки проекта: sh get_data.sh
# надо всего один раз в самом начале
#------------------------------------------------------------------------------------------------------------------------

# перходим в папку где лежит этот файл - то есть в папку проекта
cd "$(dirname "$0")"

#------------------------------------------------------------------------------------------------------------------------
# 1. качаем заправки с overpass
# вкраце, просим у сервера все заправки москвы и кладем в data/fuel.json
#------------------------------------------------------------------------------------------------------------------------

# сам запрос - все заправки (amenity=fuel) в прямоугольнике москвы на 1 сентября 2026
# четыре числа в скобках это юг запад север восток. то есть две широты и две долготы
Q='[out:json][timeout:90][date:"2026-09-01T00:00:00Z"];
nwr["amenity"="fuel"](55.55,37.30,55.95,37.90);
out center tags;'

# сервер часто занят6 поэтому пробуем до 8 раз с паузой 30 сек
# User-Agent обязателен - без него сервер шлет ошибку 406
for i in 1 2 3 4 5 6 7 8; do
  curl -sS -A "osm-moscow-study" --data-urlencode "data=$Q" https://overpass-api.de/api/interpreter -o data/fuel.json
  # если в ответе есть "elements" значит пришли нормальные данные а не ошибка
  if grep -q '"elements"' data/fuel.json 2>/dev/null; then
    echo "fuel.json ok"
    break
  fi
  echo "overpass занят, жду 30 сек ($i из 8)"
  sleep 30
done

#------------------------------------------------------------------------------------------------------------------------
# 2. качаем границу района кунцево с nominatim
# вкраце, один запрос и граница лежит в data/kuntsevo.geojson
#------------------------------------------------------------------------------------------------------------------------

# R226927 - это номер отношения (relation) кунцево на openstreetmap. нашел в адресе страницы района
curl -sS -A "osm-moscow-study" "https://nominatim.openstreetmap.org/lookup?osm_ids=R226927&polygon_geojson=1&format=geojson" -o data/kuntsevo.geojson
if grep -q 'MultiPolygon' data/kuntsevo.geojson 2>/dev/null; then
  echo "kuntsevo.geojson ok"
fi

#------------------------------------------------------------------------------------------------------------------------
# 3. делаем .venv и ставим библиотеки
# вкраце, отдельная коробка с питоном только для этого проекта.
#------------------------------------------------------------------------------------------------------------------------

# создаем .venv с питоном 3.13.
uv venv --python 3.13
# ставим то что напписано в requirements.txt - matplotlib и shapely
uv pip install -r requirements.txt

# показываем что лежит в data. там должны быть оба файла
ls -la data
