#!/bin/sh
#------------------------------------------------------------------------------------------------------------------------
# run_tests.sh - прогоняет все маленькие тестовые файлы через все команды
# все что напечаталось складываем в tests/results.txt, картинки в tests/plots
# запускать из папки проекта: sh tests/run_tests.sh
#------------------------------------------------------------------------------------------------------------------------

#------------------------------------------------------------------------------------------------------------------------
# ЧАСТЬ 1. НАСТРОЙКА
#------------------------------------------------------------------------------------------------------------------------

# переходим в папку проекта (на уровень выше папки tests)
cd "$(dirname "$0")/.."

# каким питоном запускать. по умолчанию тот что в .venv
# если нужен другой, то так: PY=python3 sh tests/run_tests.sh
PY=${PY:-.venv/bin/python}

mkdir -p tests/plots

#------------------------------------------------------------------------------------------------------------------------
# ЧАСТЬ 2. ГОНЯЕМ ВСЕ ТЕСТОВЫЕ ФАЙЛЫ ЧЕРЕЗ ВСЕ КОМАНДЫ
#------------------------------------------------------------------------------------------------------------------------

# цикл по всем файлам с точками
# каждый файл гоняем через hull, closest двумя способами, inside и plot
# район везде берем тестовый (квадрат с дыркой и второй кусок)
for t in dubl pryamaya odna dve_odinakovye dve kvadrat pustoy tochki_rayon; do
  echo "################ $t.txt"
  cat tests/$t.txt
  echo "---- hull"
  $PY geo.py hull tests/$t.txt
  echo "---- closest"
  $PY geo.py closest tests/$t.txt
  echo "---- closest --brute"
  $PY geo.py closest tests/$t.txt --brute
  echo "---- inside (район rayon_dyrka.txt)"
  $PY geo.py inside tests/$t.txt tests/rayon_dyrka.txt
  echo "---- plot"
  $PY geo.py plot tests/$t.txt tests/rayon_dyrka.txt tests/plots/$t.png
  echo
done > tests/results.txt 2>&1

#------------------------------------------------------------------------------------------------------------------------
# ЧАСТЬ 3. ПУСТОЙ РАЙОН
#------------------------------------------------------------------------------------------------------------------------

# отдельно проверяем пустой район, чтобы inside и plot не падали и без колец
echo "################ пустой район" >> tests/results.txt
$PY geo.py inside tests/dubl.txt tests/pustoy.txt >> tests/results.txt 2>&1
$PY geo.py plot tests/dubl.txt tests/pustoy.txt tests/plots/pustoy_rayon.png >> tests/results.txt 2>&1

#------------------------------------------------------------------------------------------------------------------------
# ЧАСТЬ 4. ИТОГ
#------------------------------------------------------------------------------------------------------------------------

# если где-то питон упал, в выводе будет слово Traceback
if grep -q "Traceback" tests/results.txt; then
  echo "ЧТО-ТО УПАЛО, смотри tests/results.txt"
else
  echo "все прошло без падений, вывод в tests/results.txt"
fi
